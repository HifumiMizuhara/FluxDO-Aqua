// 把 Discourse cook 管线 bundle 成裸 JS 引擎可跑的 IIFE。
//
// 源码解析规则（resolve 插件）：
//   discourse-markdown-it[/*]  → $DISCOURSE_SRC/frontend/discourse-markdown-it/src/*
//   pretty-text/*              → $DISCOURSE_SRC/frontend/pretty-text/addon/*
//   $discourse/*               → $DISCOURSE_SRC/*            （entry 里引用插件文件）
//   discourse/lib/{object,escape,case-converter} → 真实源码（无 Ember 依赖，直接用）
//   discourse/lib/deprecated   → shims/deprecated.js         （真文件依赖 @ember/debug）
//   discourse-i18n             → shims/discourse-i18n.js
//   markdown-it / xss / moment-timezone → node_modules
//
// cook 管线可达文件里未列出的 discourse/* 依赖（rsvp、later、debounce、
// dom-from-string 只被 oneboxer.js / upload-short-url.js 引用，那两个是
// web 预览的异步装饰模块，不在 cook 的 import 图内）→ 有新增会直接
// build 失败暴露，不做兜底映射。
import * as esbuild from 'esbuild';
import { execFile } from 'node:child_process';
import { readFile, stat } from 'node:fs/promises';
import { homedir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { promisify } from 'node:util';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(__dirname, '../..');
const outFile = path.join(projectRoot, 'assets/cook/discourse-cook.js');

const discourseSrc = path.resolve(
  process.env.DISCOURSE_SRC ?? path.join(homedir(), 'f/discourse'),
);
await stat(path.join(discourseSrc, 'frontend/discourse-markdown-it/src/index.js'));

// 产物头注明源 commit，锁定管线版本溯源
let discourseCommit = 'unknown';
try {
  const { stdout } = await promisify(execFile)(
    'git',
    ['-C', discourseSrc, 'rev-parse', 'HEAD'],
  );
  discourseCommit = stdout.trim();
} catch {
  /* 非 git checkout（如 tarball）时保持 unknown */
}

const SHIMS = {
  'discourse/lib/deprecated': path.join(__dirname, 'shims/deprecated.js'),
  'discourse-i18n': path.join(__dirname, 'shims/discourse-i18n.js'),
};

// 这些 discourse/lib/* 没有 Ember 依赖，直接用官方源码保证行为一致
const DISCOURSE_LIB_PASSTHROUGH = new Set([
  'discourse/lib/object',
  'discourse/lib/escape',
  'discourse/lib/case-converter',
]);

const resolvePlugin = {
  name: 'discourse-source-resolve',
  setup(build) {
    build.onResolve({ filter: /^discourse-markdown-it(\/|$)/ }, (args) => {
      const sub = args.path === 'discourse-markdown-it'
        ? 'index'
        : args.path.slice('discourse-markdown-it/'.length);
      return {
        path: path.join(
          discourseSrc,
          'frontend/discourse-markdown-it/src',
          `${sub}.js`,
        ),
      };
    });

    build.onResolve({ filter: /^pretty-text\// }, (args) => ({
      path: path.join(
        discourseSrc,
        'frontend/pretty-text/addon',
        `${args.path.slice('pretty-text/'.length)}.js`,
      ),
    }));

    build.onResolve({ filter: /^\$discourse\// }, (args) => ({
      path: path.join(discourseSrc, args.path.slice('$discourse/'.length)),
    }));

    build.onResolve({ filter: /^discourse(\/|-i18n$)/ }, (args) => {
      if (SHIMS[args.path]) {
        return { path: SHIMS[args.path] };
      }
      if (DISCOURSE_LIB_PASSTHROUGH.has(args.path)) {
        return {
          path: path.join(
            discourseSrc,
            'frontend/discourse/app',
            `${args.path.slice('discourse/'.length)}.js`,
          ),
        };
      }
      return {
        errors: [{
          text:
            `cook 管线 import 了未映射的模块 "${args.path}"` +
            `（来自 ${args.importer}）。确认它无 DOM/Ember 依赖后加进 ` +
            'DISCOURSE_LIB_PASSTHROUGH 或写 shim。',
        }],
      };
    });
  },
};

const result = await esbuild.build({
  entryPoints: [path.join(__dirname, 'src/entry.js')],
  bundle: true,
  format: 'iife',
  minify: true,
  // QuickJS(flutter_js Android/Win/Linux) 支持 ES2020+；不要降级
  // class field 等语法，保守取 es2020 足够
  target: ['es2020'],
  outfile: outFile,
  nodePaths: [path.join(__dirname, 'node_modules')],
  plugins: [resolvePlugin],
  legalComments: 'none',
  logLevel: 'warning',
  banner: {
    js:
      `/* @generated by tools/discourse-cook-bundle — do not edit by hand; run \`pnpm build\`.\n` +
      ` * source: discourse@${discourseCommit} */\n` +
      'globalThis.window ??= globalThis;',
  },
});

if (result.errors.length === 0) {
  const { size } = await stat(outFile);
  const rel = path.relative(projectRoot, outFile);
  console.log(`✓ ${rel}  ${(size / 1024).toFixed(1)} KB minified (discourse@${discourseCommit.slice(0, 10)})`);
}
